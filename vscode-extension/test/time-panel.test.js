const assert=require('assert');
const {installFakeVscode}=require('./fake-vscode');
const installed=installFakeVscode();
const {TimePanel,timeHtml}=require('../out/timePanel');
(async()=>{
 const vscode=installed.vscode;
 const original=vscode.window.createWebviewPanel;
 vscode.window.createWebviewPanel=(...args)=>({...original(...args),dispose(){}});
 const html=timeHtml();assert(html.includes("default-src 'none'"));assert(!html.includes('innerHTML'));
 const store=new Map([['manimStudio.selectedResearchSession','A']]);
 const context={subscriptions:[],workspaceState:{get:k=>store.get(k),update:async(k,v)=>store.set(k,v)}};
 const calls=[];let lose=false,active=null,onReport;
 const rpc={dispose(){},async request(method,params){calls.push({method,params:structuredClone(params)});
  if(method==='timing.status')return {ok:true,data:{session_id:params.session_id,project_id:'P',revision:1,active,intervals:[],reports:[],summary:{}}};
  if(method==='timing.contexts')return {ok:true,data:{contexts:[]}};
  if(method==='research.list')return {ok:true,data:{sessions:[{session_id:'B',title:'B'}]}};
  if(method==='timing.report'&&onReport)await onReport();
  if(lose){lose=false;throw new Error('reply lost');}
  return {ok:true,data:{}};
 }};
 const controller=new TimePanel(context,rpc);await controller.open();await controller.handle({action:'ready'});
 await controller.handle({action:'draft',session_id:'A',fields:{duration:'12'}});
 lose=true;await assert.rejects(()=>controller.handle({action:'report',seconds:12,category:'authoring'}),/reply lost/);
 const first=calls.at(-1);assert(store.get('manimStudio.time.v1').pending);
 await controller.handle({action:'choose'});assert(!calls.some(c=>c.method==='research.list'));
 await controller.handle({action:'retry'});
 assert.deepStrictEqual(calls.filter(c=>c.method==='timing.report')[1].params,first.params);
 assert(!store.get('manimStudio.time.v1').pending);assert(!store.get('manimStudio.time.v1').drafts.A);
 await controller.handle({action:'draft',session_id:'A',fields:{duration:'3'}});
 onReport=()=>controller.handle({action:'draft',session_id:'A',fields:{duration:'99'}});
 await controller.handle({action:'report',seconds:3});onReport=null;
 assert.strictEqual(store.get('manimStudio.time.v1').drafts.A.duration,'99');
 active={session_id:'A',interval_id:'I',sequence:2,owned:true,category:'authoring',measured_seconds:10};
 await controller.handle({action:'refresh'});
 lose=true;await assert.rejects(()=>controller.heartbeat(),/reply lost/);
 const uncertainBeat=store.get('manimStudio.time.v1').heartbeat.params;
 await controller.persist(s=>{s.pending={action:'report',params:{request_id:'manual-pending'}};});
 await controller.heartbeat();assert.deepStrictEqual(calls.findLast(c=>c.method==='timing.heartbeat').params,uncertainBeat);
 assert.strictEqual(store.get('manimStudio.time.v1').pending.action,'report');
 await controller.persist(s=>{s.pending=undefined;});
 vscode.window.showQuickPick=async items=>items[0];await controller.handle({action:'choose'});
 await controller.heartbeat();const beat=calls.findLast(c=>c.method==='timing.heartbeat');
 assert.strictEqual(beat.params.session_id,'A');assert.strictEqual(beat.params.sequence,3);
 assert(!calls.some(c=>c.method==='timing.transfer'));
 await controller.handle({action:'transfer',category:'classification'});
 assert.strictEqual(calls.findLast(c=>c.method==='timing.transfer').params.target_session_id,'B');
 controller.dispose();active={...active,owned:false};
 const restored=new TimePanel(context,rpc);await restored.open();await restored.handle({action:'ready'});
 const count=calls.length;await restored.heartbeat();assert.strictEqual(calls.length,count);
 assert.strictEqual(calls.findLast(c=>c.method==='timing.status').params.session_id,'B');
 assert.notStrictEqual(calls.findLast(c=>c.method==='timing.status').params.client_id,beat.params.client_id);
 restored.dispose();console.log('time panel durable drafts, exact retry, pinned selection and non-resuming ownership ok');
})().finally(()=>installed.restore()).catch(e=>{console.error(e);process.exitCode=1;});
